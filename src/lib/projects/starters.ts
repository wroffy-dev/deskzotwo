const q = (key: string, label: string, type: QuestionType, extra: { required?: boolean; options?: string[]; help?: string } = {}): Question => ({
  key,
  label,
  type,
  required: extra.required ?? false,
  options: extra.options ?? [],
  help: extra.help ?? null,
});
