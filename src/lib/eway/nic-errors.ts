function decoded(value: unknown): unknown {
  if (typeof value !== "string") return value;
  const text = value.trim();
  for (const attempt of [() => JSON.parse(Buffer.from(text, "base64").toString("utf8")), () => JSON.parse(text)]) {
    try {
      return attempt();
    } catch {
      // The next reading, or the text as it is.
    }
  }
  return text;
}

/** The codes in a refusal, in order, each once. */
export function ewayErrorCodes(body: unknown): string[] {
  const record = (body ?? {}) as { error?: unknown; ErrorDetails?: unknown };
  const error = decoded(record.error ?? record.ErrorDetails);
  const list = Array.isArray(error) ? error : [error];
  const codes = list.flatMap((e) => {
    const item = (e ?? {}) as { errorCodes?: unknown; ErrorCode?: unknown };
    return String(item.errorCodes ?? item.ErrorCode ?? "").split(",");
  });
  return [...new Set(codes.map((c) => c.trim()).filter(Boolean))];
}

/** One readable line for a refusal: each code's meaning with the code, else the message the portal gave. */
export function ewayErrorText(body: unknown): string {
  const codes = ewayErrorCodes(body);
  if (codes.length) return codes.map((c) => (EWAY_ERROR_TEXT[c] ? `${EWAY_ERROR_TEXT[c]} (${c})` : `error ${c}`)).join("; ");
  const record = (body ?? {}) as { error?: unknown; message?: unknown };
  const error = decoded(record.error);
  if (typeof error === "string" && error) return error;
  if (Array.isArray(error)) {
    const messages = error.map((e: { message?: unknown }) => (typeof e?.message === "string" ? e.message : "")).filter(Boolean);
    if (messages.length) return messages.join("; ");
  }
  if (error && typeof error === "object" && typeof (error as { message?: unknown }).message === "string") return (error as { message: string }).message;
  if (typeof record.message === "string" && record.message) return record.message;
  return "The e-way bill system refused the request.";
}
